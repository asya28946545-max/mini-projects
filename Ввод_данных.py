# Пример с запросом возраста с обработкой ошибок
while True:

    try:
        # Попытка: попробовать преобразовать ввод в целое число
        возраст = int(input("Введите свой возраст: "))
        if 0 <= возраст <= 120:
            break
        # Если строка выше выполнилась успешно, выходим из цикла

    except ValueError:
        # Исключение: если int() не сработало (например, ввели 'привет')
        print("Ошибка! Пожалуйста, введите корректное число.")

# После выхода из цикла мы гарантированно имеем число в переменной возраст
имя = input('Введите своё имя: ')
сообщение = f"Привет, {имя}! Твой возраст: {возраст}."

print(сообщение)